using System.Text;
using redb.Export.Flat.Dialects;
using redb.Export.Flat.Model;

namespace redb.Export.Flat;

/// <summary>
/// Turns a <see cref="FlatDatabaseModel"/> into DDL for one provider.
/// <para>
/// Tables are created with plain <c>CREATE TABLE</c> - never <c>IF NOT EXISTS</c> - so a name that
/// is already taken fails loudly instead of two classes sharing one table. Where the provider
/// allows it, foreign keys are separate statements meant to run after the data is loaded.
/// </para>
/// </summary>
public sealed class FlatDdlGenerator
{
    private readonly IFlatDialect _dialect;

    /// <summary>Creates a generator for a provider.</summary>
    /// <param name="providerName">Provider name as reported by <c>IDataProvider.Name</c>: <c>postgres</c>, <c>mssql</c> or <c>sqlite</c>.</param>
    public FlatDdlGenerator(string providerName)
        : this(FlatDialects.For(providerName))
    {
    }

    internal FlatDdlGenerator(IFlatDialect dialect)
    {
        _dialect = dialect;
    }

    /// <summary>The <c>CREATE TABLE</c> statement of <paramref name="table"/>.</summary>
    public string CreateTable(FlatTable table)
    {
        var lines = new List<string>();

        // Every key a writer may leave out comes from the one sequence. A scheme table is the exception:
        // its key is the id of the header row in `objects`, set by whoever writes that row.
        var keyDefault = table.Kind == FlatTableKind.Scheme ? null : _dialect.KeyDefault(FlatNaming.IdentitySequence);

        foreach (var column in table.Columns)
        {
            var type = _dialect.ColumnType(FlatStorageTypes.Of(column));
            var line = $"{_dialect.Quote(column.Name)} {type} {(column.IsNullable ? "NULL" : "NOT NULL")}";
            if (keyDefault != null && column.Role == FlatColumnRole.PrimaryKey)
                line += " " + keyDefault;
            lines.Add(line);
        }

        lines.Add($"CONSTRAINT {_dialect.Quote(table.PrimaryKeyName)} PRIMARY KEY ({_dialect.Quote(table.PrimaryKey)})");

        foreach (var unique in table.UniqueConstraints)
            lines.Add($"CONSTRAINT {_dialect.Quote(unique.Name)} UNIQUE ({string.Join(", ", unique.Columns.Select(_dialect.Quote))})");

        if (_dialect.InlineForeignKeys)
        {
            foreach (var foreignKey in table.ForeignKeys)
                lines.Add($"CONSTRAINT {_dialect.Quote(foreignKey.Name)} {ForeignKeyClause(table, foreignKey)}");
        }

        var sql = new StringBuilder();
        sql.Append("CREATE TABLE ").Append(_dialect.Quote(table.Name)).AppendLine(" (");
        sql.AppendLine("    " + string.Join("," + Environment.NewLine + "    ", lines));
        sql.Append(')');
        return sql.ToString();
    }

    /// <summary>
    /// The statements that create the plain indexes of <paramref name="table"/> (the foreign key indexes).
    /// Meant to run after the data is loaded, on every provider.
    /// </summary>
    public IReadOnlyList<string> CreateIndexes(FlatTable table) => table.Indexes
        .Select(index =>
            $"CREATE INDEX {_dialect.Quote(index.Name)} ON {_dialect.Quote(table.Name)} ({string.Join(", ", index.Columns.Select(_dialect.Quote))})")
        .ToList();

    /// <summary>
    /// The statements that add the foreign keys of <paramref name="table"/>. Empty for a provider
    /// that declares them inside <c>CREATE TABLE</c>.
    /// </summary>
    public IReadOnlyList<string> AddForeignKeys(FlatTable table)
    {
        if (_dialect.InlineForeignKeys)
            return [];

        return table.ForeignKeys
            .Select(foreignKey =>
                $"ALTER TABLE {_dialect.Quote(table.Name)} ADD CONSTRAINT {_dialect.Quote(foreignKey.Name)} {ForeignKeyClause(table, foreignKey)}")
            .ToList();
    }

    /// <summary>
    /// The statement that creates the key sequence (<see cref="FlatNaming.IdentitySequence"/>), starting at 1.
    /// Null for a provider without sequences, which generates such keys per table by itself.
    /// </summary>
    public string? CreateSequence() => _dialect.CreateSequence(FlatNaming.IdentitySequence);

    /// <summary>
    /// The statement that makes the key sequence hand out <paramref name="next"/> next: run after the
    /// data is copied, with a value above every copied key. Null for a provider without sequences.
    /// </summary>
    public string? RestartSequence(long next) => _dialect.RestartSequence(FlatNaming.IdentitySequence, next);

    /// <summary>
    /// The whole model as one script: the key sequence, every table, then every foreign key. Run on an
    /// empty database it gives the flat schema without data, with keys generated by the database. The
    /// last statement makes the client print what was created, so a run that reached the end says so.
    /// </summary>
    public string Script(FlatDatabaseModel model)
    {
        var sequence = CreateSequence();
        var foreignKeys = model.Tables.Sum(table => table.ForeignKeys.Count);
        var indexes = model.Tables.Sum(table => table.Indexes.Count);
        var summary = $"redb flat schema created: {model.Tables.Count} tables, {foreignKeys} foreign keys, {indexes} indexes, " +
                      (sequence == null ? "keys generated per table" : $"key sequence {FlatNaming.IdentitySequence}");

        var statements = (sequence == null ? Array.Empty<string>() : new[] { sequence })
            .Concat(model.Tables.Select(table => CreateTable(table)))
            .Concat(model.Tables.SelectMany(table => AddForeignKeys(table)))
            .Concat(model.Tables.SelectMany(table => CreateIndexes(table)))
            .Append(_dialect.Report(summary));

        var header = $"-- redb flat schema: {model.Tables.Count} tables, {foreignKeys} foreign keys, {indexes} indexes. Run on an empty database.";
        return header + Environment.NewLine + Environment.NewLine +
               string.Join(Environment.NewLine + Environment.NewLine, statements.Select(s => s + ";"));
    }

    private string ForeignKeyClause(FlatTable table, FlatForeignKey foreignKey)
    {
        var rule = foreignKey.OnDelete;
        // A provider that refuses a cascade from a table to itself gets the key without it; deleting a
        // parent object there means deleting its children first, as with redb on that provider.
        if (rule == FlatDeleteRule.Cascade && foreignKey.TargetTable == table.Name && !_dialect.AllowsSelfCascade)
            rule = FlatDeleteRule.NoAction;

        var onDelete = rule switch
        {
            FlatDeleteRule.Cascade => " ON DELETE CASCADE",
            FlatDeleteRule.SetNull => " ON DELETE SET NULL",
            _ => ""
        };

        return $"FOREIGN KEY ({_dialect.Quote(foreignKey.Column)}) " +
               $"REFERENCES {_dialect.Quote(foreignKey.TargetTable)} ({_dialect.Quote(foreignKey.TargetColumn)}){onDelete}";
    }
}
